export type ServiceSnapshotPolicy =
  | 'startup-critical'
  | 'persisted-local'
  | 'reactive'
  | 'command-input';

// Every Snapshot export must declare why a synchronous fallback is safe.
// Reactive consumers must converge after registration; command inputs should
// migrate to an awaited service API whenever their caller is already async.

type SnapshotExportNames<TModule> = {
  [TKey in keyof TModule]: TKey extends string
    ? TKey extends `${string}Snapshot${string}`
      ? TKey
      : never
    : never;
}[keyof TModule];

type SnapshotPolicies<TModule> = Record<
  SnapshotExportNames<TModule>,
  ServiceSnapshotPolicy
>;

