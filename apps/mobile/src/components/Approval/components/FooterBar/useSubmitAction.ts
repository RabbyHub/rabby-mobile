import {
  RcIconKeychainFaceIdCC,
  RcIconKeychainFingerprintCC,
  RcIconPasswordCC,
} from '@/assets/icons/lock';
import { AuthenticationModal } from '@/components/AuthenticationModal/AuthenticationModal';
import { useAuthenticationModal } from '@/components/AuthenticationModal/hooks';
import { apisLock } from '@/core/apis';
import { unlockTimeEvent, updateUnlockTime } from '@/core/apis/lock';
import { getPasswordIsAutoGeneratedSnapshot } from '@/core/serviceApi/preference';
import { notificationServiceApi } from '@/core/serviceApi/notification';
import { useDappSignAuthSessionIntervalMs } from '@/hooks/appSettings';
import {
  ApprovalIdentityContext,
  matchesApprovalIdentity,
} from '@/hooks/approvalIdentity';
import { useBiometrics } from '@/hooks/biometrics';
import { makeThemeIconFromCC } from '@/hooks/makeThemeIcon';
import { usePasswordStatus } from '@/hooks/useLock';
import { atom, useAtom } from 'jotai';
import React, { useMemo } from 'react';
import { useTranslation } from 'react-i18next';

const unlockTimeAtom = atom(0);
unlockTimeAtom.onMount = setter => {
  const onUnlockTimeUpdated = (value: number) => {
    setter(value);
  };

  unlockTimeEvent.addListener('updated', onUnlockTimeUpdated);
  return () => {
    unlockTimeEvent.off('updated', onUnlockTimeUpdated);
  };
};

const RcIconFaceId = makeThemeIconFromCC(
  RcIconKeychainFaceIdCC,
  'neutral-body',
);
const RcIconFingerprint = makeThemeIconFromCC(
  RcIconKeychainFingerprintCC,
  'neutral-body',
);

const RcIconPassword = makeThemeIconFromCC(RcIconPasswordCC, 'neutral-body');

export const useSubmitAction = ({
  useLastUnlockedAuth = true,
}: {
  /**
   * @description whether to use last unlock time to skip verification
   * @default true
   */
  useLastUnlockedAuth?: boolean;
} = {}) => {
  const { t } = useTranslation();
  const { computed: bioComputed } = useBiometrics();
  const { isUseCustomPwd } = usePasswordStatus();

  const [unlockTime, setUnlockTime] = useAtom(unlockTimeAtom);
  const { dappSignAuthSessionIntervalMs } = useDappSignAuthSessionIntervalMs();

  const isInAuthSession =
    Date.now() - unlockTime < dappSignAuthSessionIntervalMs;
  const isLastUnlockTimeValid = !!useLastUnlockedAuth && isInAuthSession;
  const isUnlocked = apisLock.isUnlocked();

  const disabledVerify =
    isUnlocked &&
    (isLastUnlockTimeValid ||
      (!isUseCustomPwd && !bioComputed.isBiometricsEnabled));

  const signComputed = useMemo(() => {
    return {
      needShowBioAuthIcon: bioComputed.isBiometricsEnabled,
      SubmitIcon:
        bioComputed.isBiometricsEnabled || getPasswordIsAutoGeneratedSnapshot()
          ? bioComputed.isUsingDevicePasscode
            ? !disabledVerify
              ? RcIconPassword
              : null
            : bioComputed.isFaceID
            ? RcIconFaceId
            : RcIconFingerprint
          : !disabledVerify
          ? RcIconPassword
          : null,
    };
  }, [
    bioComputed.isBiometricsEnabled,
    bioComputed.isFaceID,
    bioComputed.isUsingDevicePasscode,
    disabledVerify,
  ]);

  React.useEffect(() => {
    setUnlockTime(apisLock.getUnlockTime());
  }, [setUnlockTime]);

  const {
    currentAuthType,
    handleAuthWithBiometrics,
    prepareBioAuth,
    updateAuthType,
  } = useAuthenticationModal({
    authTypes: ['biometrics', 'password'],
  });
  const identity = React.useContext(ApprovalIdentityContext);
  const authAttemptRef = React.useRef(0);
  React.useEffect(() => {
    return () => {
      authAttemptRef.current += 1;
    };
  }, []);
  const isCurrentAttempt = React.useCallback(
    async (attempt: number) => {
      if (attempt !== authAttemptRef.current) return false;
      if (!identity) return true;
      const approval = await notificationServiceApi.getApproval();
      return (
        attempt === authAttemptRef.current &&
        matchesApprovalIdentity(approval, identity)
      );
    },
    [identity],
  );
  const onPress = React.useCallback(
    async (onFinished: () => void, onCancel: () => void) => {
      const attempt = ++authAttemptRef.current;
      const handleFinished = async () => {
        if (!(await isCurrentAttempt(attempt))) return;
        updateUnlockTime();
        onFinished();
      };

      // reset auth type to biometrics
      const handleCancel = () => {
        if (attempt !== authAttemptRef.current) return;
        authAttemptRef.current += 1;
        updateAuthType('biometrics');
        onCancel();
      };

      // avoid multiple click
      if (disabledVerify && apisLock.isUnlocked()) {
        onFinished();
        return;
      }

      // use password to verify
      const handleAuthWithPassword = async () => {
        if (!(await isCurrentAttempt(attempt))) return;
        AuthenticationModal.show({
          title: t('page.signFooterBar.confirmWithPassword'),
          onFinished: handleFinished,
          onCancel: handleCancel,
          authType: ['password'],
        });
      };
      if (currentAuthType === 'biometrics') {
        prepareBioAuth();
        return handleAuthWithBiometrics().then(result => {
          if (result.success) {
            return handleFinished();
          }
          return handleAuthWithPassword();
        });
      }
      return handleAuthWithPassword();
    },
    [
      disabledVerify,
      currentAuthType,
      updateAuthType,
      t,
      prepareBioAuth,
      handleAuthWithBiometrics,
      isCurrentAttempt,
    ],
  );

  return {
    submitText:
      disabledVerify || bioComputed.isBiometricsEnabled
        ? t('page.signFooterBar.confirm')
        : t('page.signFooterBar.confirmWithPassword'),
    SubmitIcon: !disabledVerify && signComputed.SubmitIcon,
    onPress,
  };
};
