import React from 'react';
import { act, renderHook } from '@testing-library/react-native';
import { ApprovalIdentityContext } from '@/hooks/approvalIdentity';
import { notificationServiceApi } from '@/core/serviceApi/notification';
import { updateUnlockTime } from '@/core/apis/lock';
import { useSubmitAction } from './useSubmitAction';

const mockHandleAuthWithBiometrics = jest.fn();
const mockShowAuthenticationModal = jest.fn();

jest.mock('@/assets/icons/lock', () => ({
  RcIconKeychainFaceIdCC: () => null,
  RcIconKeychainFingerprintCC: () => null,
  RcIconPasswordCC: () => null,
}));
jest.mock('@/components/AuthenticationModal/AuthenticationModal', () => ({
  AuthenticationModal: {
    show: (...args: unknown[]) => mockShowAuthenticationModal(...args),
  },
}));
jest.mock('@/components/AuthenticationModal/hooks', () => ({
  useAuthenticationModal: () => ({
    currentAuthType: 'biometrics',
    handleAuthWithBiometrics: mockHandleAuthWithBiometrics,
    prepareBioAuth: jest.fn(),
    updateAuthType: jest.fn(),
  }),
}));
jest.mock('@/core/apis', () => ({
  apisLock: {
    isUnlocked: () => true,
    getUnlockTime: () => 0,
  },
}));
jest.mock('@/core/apis/lock', () => ({
  unlockTimeEvent: { addListener: jest.fn(), off: jest.fn() },
  updateUnlockTime: jest.fn(),
}));
jest.mock('@/core/serviceApi/preference', () => ({
  getPasswordIsAutoGeneratedSnapshot: () => false,
}));
jest.mock('@/core/serviceApi/notification', () => ({
  notificationServiceApi: { getApproval: jest.fn() },
}));
jest.mock('@/hooks/appSettings', () => ({
  useDappSignAuthSessionIntervalMs: () => ({
    dappSignAuthSessionIntervalMs: 0,
  }),
}));
jest.mock('@/hooks/biometrics', () => ({
  useBiometrics: () => ({
    computed: {
      isBiometricsEnabled: true,
      isUsingDevicePasscode: false,
      isFaceID: true,
    },
  }),
}));
jest.mock('@/hooks/makeThemeIcon', () => ({
  makeThemeIconFromCC: () => () => null,
}));
jest.mock('@/hooks/useLock', () => ({
  usePasswordStatus: () => ({ isUseCustomPwd: true }),
}));
jest.mock('react-i18next', () => ({
  useTranslation: () => ({ t: (key: string) => key }),
}));

const approvalA = {
  id: 'approval-a',
  data: { approvalComponent: 'SignText' },
};
const approvalB = {
  id: 'approval-b',
  data: { approvalComponent: 'SignTypedData' },
};
const wrapper = ({ children }: { children: React.ReactNode }) => (
  <ApprovalIdentityContext.Provider
    value={{ id: approvalA.id, component: 'SignText' }}>
    {children}
  </ApprovalIdentityContext.Provider>
);

beforeEach(() => {
  jest.clearAllMocks();
  jest
    .mocked(notificationServiceApi.getApproval)
    .mockResolvedValue(approvalA as never);
});

test('drops biometric completion after cancellation promotes another approval', async () => {
  let completeBiometrics!: (result: { success: boolean }) => void;
  mockHandleAuthWithBiometrics.mockImplementation(
    () =>
      new Promise<{ success: boolean }>(resolve => {
        completeBiometrics = resolve;
      }),
  );
  const onFinished = jest.fn();
  const { result } = renderHook(() => useSubmitAction(), { wrapper });
  let completion!: Promise<void>;
  act(() => {
    completion = result.current.onPress(onFinished, jest.fn()) as Promise<void>;
  });

  jest
    .mocked(notificationServiceApi.getApproval)
    .mockResolvedValue(approvalB as never);
  await act(async () => {
    completeBiometrics({ success: true });
    await completion;
  });

  expect(onFinished).not.toHaveBeenCalled();
  expect(updateUnlockTime).not.toHaveBeenCalled();
  expect(mockShowAuthenticationModal).not.toHaveBeenCalled();
});

test('resolves only the approval that completed biometric authentication', async () => {
  let completeBiometrics!: (result: { success: boolean }) => void;
  mockHandleAuthWithBiometrics.mockImplementation(
    () =>
      new Promise<{ success: boolean }>(resolve => {
        completeBiometrics = resolve;
      }),
  );
  const onFinished = jest.fn();
  const { result } = renderHook(() => useSubmitAction(), { wrapper });
  let completion!: Promise<void>;
  act(() => {
    completion = result.current.onPress(onFinished, jest.fn()) as Promise<void>;
  });

  await act(async () => {
    completeBiometrics({ success: true });
    await completion;
  });

  expect(onFinished).toHaveBeenCalledTimes(1);
  expect(updateUnlockTime).toHaveBeenCalledTimes(1);
});

test('password cancellation invalidates a later success callback', async () => {
  mockHandleAuthWithBiometrics.mockResolvedValue({ success: false });
  const onFinished = jest.fn();
  const onCancel = jest.fn();
  const { result } = renderHook(() => useSubmitAction(), { wrapper });

  await act(async () => {
    await result.current.onPress(onFinished, onCancel);
  });
  const authentication = mockShowAuthenticationModal.mock.calls[0][0];
  act(() => {
    authentication.onCancel();
  });
  await act(async () => {
    await authentication.onFinished();
  });

  expect(onCancel).toHaveBeenCalledTimes(1);
  expect(onFinished).not.toHaveBeenCalled();
  expect(updateUnlockTime).not.toHaveBeenCalled();
});
