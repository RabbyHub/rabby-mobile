describe('legacy authentication native-dismiss handoff', () => {
  beforeEach(() => {
    jest.useFakeTimers();
    mockClose.mockClear();
    mockPresent.mockClear();
    mockNativeDismiss.clear();
  });
  afterEach(() => {
    jest.clearAllTimers();
    jest.useRealTimers();
  });

  async function openFlow() {
    const view = render(<GlobalBottomSheetModal />);
    const onFinished = jest.fn();
    const onDismiss = jest.fn();
    const onCancel = jest.fn();
    let controls!: Awaited<ReturnType<typeof AuthenticationModal.show>>;
    let id = '';
    const captureId = (createdId: string) => {
      id = createdId;
    };
    globalSheetModalEvents.on(EVENT_NAMES.CREATE, captureId);
    try {
      await act(async () => {
        controls = await AuthenticationModal.show({
          title: 'Fixture account removal',
          authType: ['none'],
          onFinished,
          onDismiss,
          onCancel,
        });
      });
    } finally {
      globalSheetModalEvents.off(EVENT_NAMES.CREATE, captureId);
    }
    act(() => jest.advanceTimersByTime(100));
    expect(mockPresent).toHaveBeenCalledTimes(1);
    const dismiss = mockNativeDismiss.get(id)!;
    return { view, controls, id, dismiss, onFinished, onDismiss, onCancel };
  }

  it('keeps the owner mounted and delays success until native dismissal', async () => {
    const flow = await openFlow();
    const closed = jest.fn();
    globalSheetModalEvents.on(EVENT_NAMES.CLOSED, closed);
    try {
      fireEvent.press(flow.view.getByText('global.Confirm'));
      expect(mockClose).toHaveBeenCalledWith({ duration: 300 });
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(closed).not.toHaveBeenCalled();
      expect(flow.view.getByTestId('native-sheet-owner')).toBeTruthy();

      fireEvent.press(flow.view.getByText('global.Confirm'));
      expect(mockClose).toHaveBeenCalledTimes(1);
      act(flow.dismiss);
      expect(flow.view.queryByTestId('native-sheet-owner')).toBeNull();
      expect(closed).toHaveBeenCalledWith(flow.id);
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
      expect(flow.onFinished.mock.invocationCallOrder[0]).toBeLessThan(
        flow.onDismiss.mock.invocationCallOrder[0],
      );
      act(flow.dismiss);
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
    } finally {
      flow.view.unmount();
      globalSheetModalEvents.off(EVENT_NAMES.CLOSED, closed);
    }
  });

  it('keeps the host and close waiter until that native sheet dismisses', async () => {
    const flow = await openFlow();
    const settled = jest.fn();
    const closeOptions = { duration: 300, waitForDismiss: true };
    try {
      act(() => {
        void apisAppWin
          .removeGlobalBottomSheetModal(flow.id, closeOptions)
          .then(settled);
      });
      expect(flow.view.getByTestId('native-sheet-owner')).toBeTruthy();
      expect(mockClose).toHaveBeenCalledWith({ duration: 300 });
      await act(async () => {});
      expect(settled).not.toHaveBeenCalled();
      await act(async () => flow.dismiss());
      expect(flow.view.queryByTestId('native-sheet-owner')).toBeNull();
      expect(settled).toHaveBeenCalledWith(flow.id);
      expect(flow.onFinished).not.toHaveBeenCalled();
    } finally {
      flow.view.unmount();
    }
  });

  it('cancels a queued result synchronously when keyring lock closes the sheet', async () => {
    const flow = await openFlow();
    const closedListenersBefore = globalSheetModalEvents.listenerCount(
      EVENT_NAMES.CLOSED,
    );
    const handleLock = jest
      .mocked(bindKeyringEventAfterRegistration)
      .mock.calls.find(([event]) => event === 'lock')?.[1];
    expect(handleLock).toBeDefined();
    try {
      fireEvent.press(flow.view.getByText('global.Confirm'));
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(flow.view.getByTestId('native-sheet-owner')).toBeTruthy();
      mockClose.mockImplementationOnce(flow.dismiss);
      act(() => {
        // Also exercise a zero-duration/native-immediate completion *inside*
        // close(): cancellation must run before the host calls that method.
        (handleLock as () => void)();
        // Native dismissal may arrive before React commits the lock cleanup.
        flow.dismiss();
      });
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(flow.view.queryByTestId('native-sheet-owner')).toBeNull();
      expect(globalSheetModalEvents.listenerCount(EVENT_NAMES.CLOSED)).toBe(
        closedListenersBefore,
      );
    } finally {
      flow.view.unmount();
    }
  });

  it('releases a close waiter if the whole host unmounts without native onDismiss', async () => {
    const flow = await openFlow();
    const closedListenersBefore = globalSheetModalEvents.listenerCount(
      EVENT_NAMES.CLOSED,
    );
    try {
      fireEvent.press(flow.view.getByText('global.Confirm'));
      expect(globalSheetModalEvents.listenerCount(EVENT_NAMES.CLOSED)).toBe(
        closedListenersBefore + 1,
      );
      act(() => flow.view.unmount());
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(globalSheetModalEvents.listenerCount(EVENT_NAMES.CLOSED)).toBe(
        closedListenersBefore,
      );
    } finally {
      // Test isolation only: the assertion above does not depend on this late
      // callback, which a destroyed native host may never deliver.
      act(flow.dismiss);
      flow.view.unmount();
    }
  });

  it.each(['cancel', 'hide', 'host-unmount'] as const)(
    'discards a queued success after %s, even if native dismiss arrives late',
    async cancellation => {
      const flow = await openFlow();
      try {
        fireEvent.press(flow.view.getByText('global.Confirm'));
        expect(flow.onFinished).not.toHaveBeenCalled();
        act(() => {
          if (cancellation === 'cancel') {
            fireEvent.press(flow.view.getByText('global.Cancel'));
          } else if (cancellation === 'hide') {
            void flow.controls.hideModal();
          } else {
            flow.view.unmount();
          }
        });
        act(flow.dismiss);
        expect(flow.onFinished).not.toHaveBeenCalled();
        expect(flow.onCancel).toHaveBeenCalledTimes(
          cancellation === 'cancel' ? 1 : 0,
        );
      } finally {
        flow.view.unmount();
      }
    },
  );
});
