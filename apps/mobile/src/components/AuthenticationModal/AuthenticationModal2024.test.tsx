import React from 'react';
import { act, fireEvent, render } from '@testing-library/react-native';
import { View } from 'react-native';
import { Text } from '@/components/Typography';
import { AuthenticationModal2024 } from './AuthenticationModal2024';

const mockCreate = jest.fn();
const mockRemove = jest.fn(() => Promise.resolve());
const mockRequestPassword = jest.fn();
jest.mock('react-i18next', () => ({
  useTranslation: () => ({ t: (key: string) => key }),
}));
jest.mock('@/components2024/GlobalBottomSheetModal', () => ({
  createGlobalBottomSheetModal2024: (...args: unknown[]) => mockCreate(...args),
  removeGlobalBottomSheetModal2024: (...args: unknown[]) => mockRemove(...args),
}));
jest.mock('@/core/apis', () => ({
  apisKeychain: {
    requestGenericPassword: (...args: unknown[]) =>
      mockRequestPassword(...args),
    RequestGenericPurpose: { DECRYPT_PWD: 'decrypt' },
  },
  apisLock: {
    getRabbyLockInfo: async () => ({ isUseCustomPwd: true }),
    verifyPasswordOrUnlock: jest.fn(),
    updateUnlockTime: jest.fn(),
  },
}));
jest.mock('@/core/serviceApi/preference', () => ({
  getPasswordIsAutoGeneratedSnapshot: () => false,
}));
jest.mock('@/core/native/utils', () => ({ IS_IOS: true }));
jest.mock('@/hooks/theme', () => ({
  useTheme2024: () => ({ styles: {}, colors2024: {} }),
}));
jest.mock('@/hooks/useLock', () => ({
  useLoadLockInfo: jest.fn(),
  usePasswordStatus: () => ({ isUseCustomPwd: true }),
}));
jest.mock('@/utils/styles', () => ({
  createGetStyles2024: (fn: unknown) => fn,
}));
jest.mock('./BiometricsIcon', () => ({ BiometricsIcon: () => null }));
jest.mock('./CheckItem', () => ({ CheckItem: () => null }));
jest.mock('../Touchable/TouchableView', () => require('react-native').View);
jest.mock('@/hooks/biometrics', () => ({
  useBiometricsComputed: () => ({ isBiometricsEnabled: true }),
}));
jest.mock('@/hooks/useAppLayout', () => ({
  useSafeAndroidBottomSizes: () => ({ safeSizes: {} }),
}));
jest.mock('@/components2024/Button', () => ({
  Button: ({ title, onPress }: any) => {
    const Native = require('react-native');
    return <Native.Text onPress={onPress}>{title}</Native.Text>;
  },
}));
jest.mock('./hooks', () => ({
  ...jest.requireActual('./authType'),
  BioAuthStage: { idle: 0, prepare: 1, authenticating: 2 },
  useAuthTypeSelection: () => {
    const [currentAuthType, setCurrentAuthType] =
      require('react').useState('biometrics');
    return { currentAuthType, setCurrentAuthType };
  },
}));
jest.mock('../AutoLockView', () => require('react-native').View);
jest.mock('@/constant', () => ({ APP_TEST_PWD: '' }));
jest.mock('@/components2024/Form/Input', () => ({
  NextInput: { Password: () => null },
}));
jest.mock('@/components/Typography', () => ({
  Text: require('react-native').Text,
}));

describe('authentication sheet to manual backup handoff', () => {
  beforeEach(() => {
    jest.useFakeTimers();
    mockCreate.mockReset().mockReturnValue('AUTHENTICATION_backup');
    mockRemove.mockClear();
    mockRequestPassword.mockReset().mockImplementation(async options => {
      await options.onPlainPassword('fixture-password');
    });
  });
  afterEach(() => jest.useRealTimers());

  async function openBackupFlow(
    validationHandler = jest.fn(async () => undefined),
  ) {
    let sheet: any;
    let controls: Awaited<ReturnType<typeof AuthenticationModal2024.show>>;
    const onDismiss = jest.fn();
    const onCancel = jest.fn();
    const onFinished = jest.fn();
    function Flow() {
      const [backup, setBackup] = React.useState(false);
      const [auth, setAuth] = React.useState<any>();
      React.useEffect(() => {
        mockCreate.mockImplementation(params => {
          sheet = params;
          setAuth(params);
          return 'AUTHENTICATION_backup';
        });
        void AuthenticationModal2024.show({
          title: 'Verify backup',
          confirmText: 'Verify and back up',
          validationHandler,
          onFinished: ctx => {
            onFinished(ctx);
            setBackup(true);
          },
          onDismiss,
          onCancel,
        }).then(result => {
          controls = result;
        });
      }, []);
      return (
        <View>
          {auth && <AuthenticationModal2024 {...auth} $createParams={auth} />}
          {backup && <Text>Manual backup content</Text>}
        </View>
      );
    }
    const view = render(<Flow />);
    await act(async () => {});
    const confirm = async () => {
      fireEvent.press(view.getByText('Verify and back up'));
      await act(async () => {
        jest.advanceTimersByTime(100);
      });
    };
    return {
      view,
      confirm,
      get sheet() {
        return sheet;
      },
      get controls() {
        return controls!;
      },
      onDismiss,
      onCancel,
      onFinished,
      validationHandler,
    };
  }

  it('does not replace the native auth sheet until its own dismiss completes', async () => {
    const flow = await openBackupFlow();
    await flow.confirm();
    expect(flow.validationHandler).toHaveBeenCalledWith('fixture-password');
    expect(flow.view.queryByText('Manual backup content')).toBeNull();
    expect(mockRemove).toHaveBeenCalledWith('AUTHENTICATION_backup', {
      duration: 0,
      waitForDismiss: true,
    });
    await flow.confirm();
    expect(mockRemove).toHaveBeenCalledTimes(1);
    act(() => flow.sheet.bottomSheetModalProps.onDismiss());
    expect(flow.view.getByText('Manual backup content')).toBeTruthy();
    act(() => flow.sheet.bottomSheetModalProps.onDismiss());
    expect(flow.onDismiss).toHaveBeenCalledTimes(1);
    expect(flow.onFinished).toHaveBeenCalledTimes(1);
    expect(flow.onFinished.mock.invocationCallOrder[0]).toBeLessThan(
      flow.onDismiss.mock.invocationCallOrder[0],
    );
  });

  it('contains a caller success error after dismiss without retrying the result', async () => {
    const logError = jest
      .spyOn(console, 'error')
      .mockImplementation(() => undefined);
    try {
      const flow = await openBackupFlow();
      const callbackError = new Error('fixture success callback failed');
      flow.onFinished.mockImplementation(() => {
        throw callbackError;
      });

      await flow.confirm();
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(flow.onDismiss).not.toHaveBeenCalled();
      expect(() =>
        act(() => flow.sheet.bottomSheetModalProps.onDismiss()),
      ).not.toThrow();
      expect(logError).toHaveBeenCalledTimes(1);
      expect(logError).toHaveBeenCalledWith(callbackError);
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
      expect(flow.onFinished.mock.invocationCallOrder[0]).toBeLessThan(
        flow.onDismiss.mock.invocationCallOrder[0],
      );

      act(() => flow.sheet.bottomSheetModalProps.onDismiss());
      await flow.confirm();
      act(() => flow.sheet.bottomSheetModalProps.onDismiss());
      expect(mockRemove).toHaveBeenCalledTimes(1);
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
      expect(logError).toHaveBeenCalledTimes(1);
      expect(flow.view.queryByText('Manual backup content')).toBeNull();
    } finally {
      logError.mockRestore();
    }
  });

  it('does not catch an error from the caller dismiss callback', async () => {
    const logError = jest
      .spyOn(console, 'error')
      .mockImplementation(() => undefined);
    try {
      const flow = await openBackupFlow();
      const dismissError = new Error('fixture dismiss callback failed');
      flow.onDismiss.mockImplementation(() => {
        throw dismissError;
      });

      await flow.confirm();
      expect(() =>
        act(() => flow.sheet.bottomSheetModalProps.onDismiss()),
      ).toThrow(dismissError);
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
      expect(logError).not.toHaveBeenCalled();

      expect(() =>
        act(() => flow.sheet.bottomSheetModalProps.onDismiss()),
      ).not.toThrow();
      expect(flow.onFinished).toHaveBeenCalledTimes(1);
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
    } finally {
      logError.mockRestore();
    }
  });

  it('ignores successful authentication after an explicit hide', async () => {
    const flow = await openBackupFlow();
    act(() => {
      void flow.controls.hideModal();
    });
    await flow.confirm();
    act(() => flow.sheet.bottomSheetModalProps.onDismiss());
    expect(flow.view.queryByText('Manual backup content')).toBeNull();
  });

  it('does not show sensitive content if authentication finishes after the auth sheet unmounts', async () => {
    let resolveValidation!: () => void;
    const validation = jest.fn(
      () =>
        new Promise<void>(resolve => {
          resolveValidation = resolve;
        }),
    );
    const flow = await openBackupFlow(validation);
    await flow.confirm();
    flow.view.unmount();
    await act(async () => {
      resolveValidation();
    });
    expect(mockRemove).not.toHaveBeenCalled();
  });

  it('discards a pending handoff if the auth sheet unmounts during native close', async () => {
    const flow = await openBackupFlow();
    await flow.confirm();
    flow.view.unmount();
    act(() => flow.sheet.bottomSheetModalProps.onDismiss());
    expect(flow.onFinished).not.toHaveBeenCalled();
  });

  it.each(['cancel', 'swipe'] as const)(
    'does not reopen backup after %s while Face ID is finishing',
    async dismissal => {
      let resolveValidation!: () => void;
      const flow = await openBackupFlow(
        jest.fn(
          () =>
            new Promise<void>(resolve => {
              resolveValidation = resolve;
            }),
        ),
      );
      await flow.confirm();
      act(() => {
        if (dismissal === 'cancel') {
          flow.sheet.onCancel();
        }
        flow.sheet.bottomSheetModalProps.onDismiss();
      });
      await act(async () => {
        resolveValidation();
      });
      expect(flow.view.queryByText('Manual backup content')).toBeNull();
      expect(flow.onFinished).not.toHaveBeenCalled();
      expect(flow.onDismiss).toHaveBeenCalledTimes(1);
    },
  );

  it('does not start a handoff when validation fails', async () => {
    const error = jest
      .spyOn(console, 'error')
      .mockImplementation(() => undefined);
    try {
      const flow = await openBackupFlow(
        jest.fn(async () => {
          throw new Error('fixture validation failed');
        }),
      );
      await flow.confirm();
      expect(mockRemove).not.toHaveBeenCalled();
      expect(flow.view.queryByText('Manual backup content')).toBeNull();
    } finally {
      error.mockRestore();
    }
  });
});
