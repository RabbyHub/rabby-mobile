describe('hooks/biometrics', () => {
  const KEYCHAIN_AUTH_TYPES = {
    APPLICATION_PASSWORD: 0,
    BIOMETRICS: 1,
    PASSCODE: 2,
    REMEMBER_ME: 3,
    BIOMETRICS_OR_PASSCODE: 4,
  };
  const RequestGenericPurpose = {
    VERIFY: 1,
    DECRYPT_PWD: 11,
  };

  const setup = async ({
    authType = KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
    authenticatedByBiometrics = true,
    supportedBiometryType = null as string | null,
    passcodeAuthAvailable = true,
    pinOrFingerprintSet = passcodeAuthAvailable,
    passwordIsAutoGenerated = false,
    passwordState = undefined as
      | import('@rabby-wallet/service-keyring').KeyringPasswordState
      | undefined,
    isIOS = false,
  } = {}) => {
    jest.resetModules();

    let currentAuthType = authType;
    let currentAuthenticatedByBiometrics = authenticatedByBiometrics;
    let currentPasswordIsAutoGenerated = passwordIsAutoGenerated;
    let currentPasswordState = passwordState;

    const mockSetGenericPassword = jest.fn(async () => undefined);
    const mockRequestGenericPassword = jest.fn(async () => ({
      actionSuccess: true,
    }));
    const mockResetGenericPassword = jest.fn(async () => {
      currentAuthType = KEYCHAIN_AUTH_TYPES.APPLICATION_PASSWORD;
      currentAuthenticatedByBiometrics = false;
      return true;
    });
    const mockSetPasswordIsAutoGeneratedDurably = jest.fn(
      async (value: boolean) => {
        currentPasswordIsAutoGenerated = value;
      },
    );
    const mockSetKeyringPasswordState = jest.fn(async value => {
      currentPasswordState = value;
    });
    const mockCompleteKeyringAuthTransition = jest.fn(async () => {
      if (currentPasswordState) {
        currentPasswordState = {
          ...currentPasswordState,
          pendingAuthTransition: undefined,
        };
      }
      return true;
    });
    const mockGetSupportedBiometryType = jest.fn(
      async () => supportedBiometryType,
    );
    const mockIsPasscodeAuthAvailable = jest.fn(
      async () => passcodeAuthAvailable,
    );
    const mockIsPinOrFingerprintSet = jest.fn(async () => pinOrFingerprintSet);
    const mockGetKeychainDebugState = jest.fn(async () => ({
      platform: 'android',
      debugSupported: true,
      hasEntry: true,
      hasUsername: true,
      hasPassword: true,
      sourceLabel: 'test-keychain',
      resolvedCipherStorageName: 'KeystoreAESGCM_NoAuth',
      hasKeystoreAlias: true,
    }));
    const mockGetKeychainEntryState = jest.fn(async () => ({
      service: 'com.debank',
      hasEntry: true,
      hasUsername: true,
      hasPassword: true,
      sourceLabel: 'test-keychain',
    }));

    jest.doMock('@rabby-wallet/react-native-keychain', () => ({
      BIOMETRY_TYPE: {
        FACE_ID: 'FaceID',
      },
    }));
    jest.doMock('react-i18next', () => ({
      useTranslation: () => ({
        t: (key: string) => key,
      }),
    }));
    jest.doMock('@/core/native/utils', () => ({
      IS_ANDROID: !isIOS,
      IS_IOS: isIOS,
    }));
    jest.doMock('@/constant', () => ({
      isNonPublicProductionEnv: true,
    }));
    jest.doMock('@/core/storage/mmkv', () => ({
      zustandByMMKV: <T extends object>(_key: string, initialState: T) => {
        let state = initialState;
        const store = ((selector: (input: T) => unknown) =>
          selector(state)) as ((selector: (input: T) => unknown) => unknown) & {
          getState: () => T;
          setState: (updater: T | ((prev: T) => T)) => void;
        };

        store.getState = () => state;
        store.setState = updater => {
          state =
            typeof updater === 'function'
              ? (updater as (prev: T) => T)(state)
              : updater;
        };
        return store;
      },
    }));
    jest.doMock('@/core/apis/keychain', () => ({
      KEYCHAIN_AUTH_TYPES,
      RequestGenericPurpose,
      getAuthenticationType: jest.fn(() => currentAuthType),
      getSupportedBiometryType: mockGetSupportedBiometryType,
      isPasscodeAuthAvailable: mockIsPasscodeAuthAvailable,
      getKeychainDebugState: mockGetKeychainDebugState,
      getKeychainEntryState: mockGetKeychainEntryState,
      getDefaultBiometricsAuthenticationType: jest.fn(
        () => KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      ),
      setGenericPassword: mockSetGenericPassword,
      requestGenericPassword: mockRequestGenericPassword,
      resetGenericPassword: mockResetGenericPassword,
      isAuthenticatedByBiometrics: jest.fn(
        () => currentAuthenticatedByBiometrics,
      ),
      parseKeychainError: jest.fn(() => ({
        isCancelledByUser: false,
        sysMessage: '',
      })),
    }));
    jest.doMock('@/core/apis/lock', () => ({
      ensureKeyringRuntimeReady: jest.fn(async () => undefined),
      parseValidationBehavior: jest.fn(),
    }));
    jest.doMock('@/core/serviceApi/preference', () => ({
      getPasswordIsAutoGenerated: jest.fn(
        async () => currentPasswordIsAutoGenerated,
      ),
      getPasswordIsAutoGeneratedSnapshot: jest.fn(
        () => currentPasswordIsAutoGenerated,
      ),
      setPasswordIsAutoGeneratedDurably: mockSetPasswordIsAutoGeneratedDurably,
    }));
    jest.doMock('@/core/serviceApi/keyring', () => ({
      getKeyringPasswordState: jest.fn(async () => currentPasswordState),
      setKeyringPasswordState: mockSetKeyringPasswordState,
      completeKeyringAuthTransition: mockCompleteKeyringAuthTransition,
    }));
    jest.doMock('@/components2024/Toast', () => ({
      toast: {
        show: jest.fn(),
        info: jest.fn(),
        success: jest.fn(),
        error: jest.fn(),
      },
      toastLoading: jest.fn(() => jest.fn()),
    }));
    jest.doMock('@/utils/logger', () => ({
      logger: {
        info: jest.fn(),
        warn: jest.fn(),
      },
    }));
    jest.doMock('react-native-haptic-feedback', () => ({
      trigger: jest.fn(),
    }));
    jest.doMock('react-native-device-info', () => ({
      __esModule: true,
      default: {
        isPinOrFingerprintSet: mockIsPinOrFingerprintSet,
      },
    }));

    const module = require('./biometrics') as typeof import('./biometrics');
    await Promise.resolve();

    return {
      module,
      mockSetGenericPassword,
      mockRequestGenericPassword,
      mockGetSupportedBiometryType,
      mockIsPasscodeAuthAvailable,
      mockIsPinOrFingerprintSet,
      mockGetKeychainEntryState,
      mockGetKeychainDebugState,
      mockResetGenericPassword,
      mockSetPasswordIsAutoGeneratedDurably,
      mockSetKeyringPasswordState,
      mockCompleteKeyringAuthTransition,
    };
  };

  afterEach(() => {
    jest.restoreAllMocks();
  });

  it('keeps settings on biometrics when only Android passcode is available but not enabled', async () => {
    const { module } = await setup();

    const computed = module.computeBiometricsState({
      authEnabled: false,
      supportedBiometryType: null,
      devicePasscodeAvailable: true,
      authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      passwordIsAutoGenerated: false,
      t: (key: string) => key,
      isIOS: false,
    });

    expect(computed.couldSetupBiometrics).toBe(false);
    expect(computed.couldSetupSystemAuth).toBe(true);
    expect(computed.isBiometricsEnabled).toBe(false);
    expect(computed.isUsingDevicePasscode).toBe(false);
    expect(computed.isUsingDevicePasscodeForSettings).toBe(false);
    expect(computed.isDevicePasscodeOnlyAvailable).toBe(true);
    expect(computed.systemAuthSettingsLabel).toBe('page.setting.fingerPrint');
    expect(computed.systemAuthTypeLabel).toBe('page.setting.fingerPrint');
  });

  it('enables passcode-capable system auth for autogenerated passwords when only Android passcode is available', async () => {
    const {
      module,
      mockSetGenericPassword,
      mockRequestGenericPassword,
      mockGetSupportedBiometryType,
      mockIsPasscodeAuthAvailable,
    } = await setup({
      passwordIsAutoGenerated: true,
    });

    const changed = await module.storeApisBiometrics.toggleBiometrics(true, {
      validatedPassword: 'plain-password',
    });

    expect(changed).toBe(true);
    expect(mockSetGenericPassword).toHaveBeenCalledWith(
      'plain-password',
      KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
    );
    expect(mockRequestGenericPassword).toHaveBeenCalledWith({
      purpose: RequestGenericPurpose.VERIFY,
    });
    expect(mockGetSupportedBiometryType).toHaveBeenCalled();
    expect(mockIsPasscodeAuthAvailable).toHaveBeenCalled();

    const computed = module.computeBiometricsState({
      authEnabled: true,
      supportedBiometryType: null,
      devicePasscodeAvailable: true,
      authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      passwordIsAutoGenerated: true,
      t: (key: string) => key,
      isIOS: false,
    });
    expect(computed.isBiometricsEnabled).toBe(true);
    expect(computed.isUsingDevicePasscode).toBe(true);
    expect(computed.isUsingDevicePasscodeForSettings).toBe(true);
    expect(computed.isDevicePasscodeOnlyAvailable).toBe(true);
    expect(computed.systemAuthTypeLabel).toBe('page.setting.devicePassword');
    expect(computed.systemAuthSettingsLabel).toBe(
      'page.setting.useDevicePassword',
    );
    expect(computed.systemAuthSwitchTypeLabel).toBe(
      'page.setting.useDevicePassword',
    );
  });

  it('does not use Android passcode fallback for custom-password unlock when biometrics are unavailable', async () => {
    const { module } = await setup({
      authenticatedByBiometrics: true,
      supportedBiometryType: null,
      passcodeAuthAvailable: true,
      pinOrFingerprintSet: true,
      passwordIsAutoGenerated: false,
    });

    const computed = module.computeBiometricsState({
      authEnabled: true,
      supportedBiometryType: null,
      devicePasscodeAvailable: true,
      authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      passwordIsAutoGenerated: false,
      t: (key: string) => key,
      isIOS: false,
    });

    expect(computed.isBiometricsEnabled).toBe(false);
    expect(computed.isUsingDevicePasscode).toBe(false);
    expect(computed.systemAuthTypeLabel).toBe('page.setting.fingerPrint');
    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(false);
  });

  it('shows device password in settings only for autogenerated passwords', async () => {
    const { module } = await setup();

    const computed = module.computeBiometricsState({
      authEnabled: true,
      supportedBiometryType: null,
      devicePasscodeAvailable: true,
      authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      passwordIsAutoGenerated: true,
      t: (key: string) => key,
      isIOS: false,
    });

    expect(computed.isUsingDevicePasscode).toBe(true);
    expect(computed.isUsingDevicePasscodeForSettings).toBe(true);
    expect(computed.systemAuthTypeLabel).toBe('page.setting.devicePassword');
    expect(computed.systemAuthSettingsLabel).toBe(
      'page.setting.useDevicePassword',
    );
  });

  it('finishes a persisted biometric-disable transition before unlock', async () => {
    const {
      module,
      mockResetGenericPassword,
      mockSetPasswordIsAutoGeneratedDurably,
      mockCompleteKeyringAuthTransition,
    } = await setup({
      authenticatedByBiometrics: true,
      authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
      passwordIsAutoGenerated: true,
      passwordState: {
        version: 1,
        origin: 'user',
        pendingAuthTransition: 'disable-biometrics',
      },
    });

    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(false);
    expect(mockSetPasswordIsAutoGeneratedDurably).toHaveBeenCalledWith(false);
    expect(mockResetGenericPassword).toHaveBeenCalledTimes(1);
    expect(mockCompleteKeyringAuthTransition).toHaveBeenCalledWith(
      'disable-biometrics',
    );
  });

  it('heals a legacy partial disable before settings consume the state', async () => {
    const {
      module,
      mockSetPasswordIsAutoGeneratedDurably,
      mockSetKeyringPasswordState,
    } = await setup({
      authenticatedByBiometrics: false,
      authType: KEYCHAIN_AUTH_TYPES.APPLICATION_PASSWORD,
      passwordIsAutoGenerated: true,
    });

    await module.reconcileBiometricAuthState();

    expect(mockSetKeyringPasswordState).toHaveBeenCalledWith({
      version: 1,
      origin: 'user',
    });
    expect(mockSetPasswordIsAutoGeneratedDurably).toHaveBeenCalledWith(false);
  });

  it('uses Android keyguard secure state when keychain passcode probing is unavailable', async () => {
    const { module } = await setup({
      authenticatedByBiometrics: true,
      supportedBiometryType: null,
      passcodeAuthAvailable: false,
      pinOrFingerprintSet: true,
      passwordIsAutoGenerated: true,
    });

    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(true);
  });

  it('uses the lightweight Android keychain entry probe before unlock', async () => {
    const { module, mockGetKeychainEntryState, mockGetKeychainDebugState } =
      await setup({
        supportedBiometryType: 'Fingerprint',
      });

    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(true);

    expect(mockGetKeychainEntryState).toHaveBeenCalledTimes(1);
    expect(mockGetKeychainDebugState).not.toHaveBeenCalled();
  });

  it('uses iOS owner authentication policy for device passcode availability', async () => {
    const { module, mockIsPasscodeAuthAvailable, mockIsPinOrFingerprintSet } =
      await setup({
        isIOS: true,
        authenticatedByBiometrics: true,
        supportedBiometryType: null,
        passcodeAuthAvailable: true,
        passwordIsAutoGenerated: true,
      });

    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(true);
    expect(mockIsPasscodeAuthAvailable).toHaveBeenCalled();
    expect(mockIsPinOrFingerprintSet).not.toHaveBeenCalled();
  });

  it('mocks no usable system authentication', async () => {
    const { module } = await setup({
      supportedBiometryType: 'Fingerprint',
      passcodeAuthAvailable: true,
    });

    const changed = module.setBiometricsSystemAuthDebugMode(
      module.BIOMETRICS_SYSTEM_AUTH_DEBUG_MODES.NONE,
    );

    expect(changed).toBe(true);
    expect(
      module.applyBiometricsSystemAuthDebugMock({
        supportedBiometryType: null,
        devicePasscodeAvailable: true,
      }),
    ).toEqual({
      supportedBiometryType: null,
      devicePasscodeAvailable: false,
    });
  });

  it('mocks no biometrics while keeping device passcode available', async () => {
    const { module } = await setup({
      supportedBiometryType: 'Fingerprint',
      passcodeAuthAvailable: false,
      pinOrFingerprintSet: false,
      passwordIsAutoGenerated: true,
    });

    const changed = module.setBiometricsSystemAuthDebugMode(
      module.BIOMETRICS_SYSTEM_AUTH_DEBUG_MODES.NO_BIOMETRICS_DEVICE_PASSCODE,
    );

    expect(changed).toBe(true);
    expect(
      module.applyBiometricsSystemAuthDebugMock({
        supportedBiometryType: 'Fingerprint',
        devicePasscodeAvailable: false,
      }),
    ).toEqual({
      supportedBiometryType: null,
      devicePasscodeAvailable: true,
    });
    await expect(
      module.storeApisBiometrics.ensureBiometricsReadyForUnlock(),
    ).resolves.toBe(true);
  });

  it('labels iOS Face ID and Touch ID from the detected biometry type', async () => {
    const { module } = await setup();

    expect(
      module.computeBiometricsState({
        authEnabled: true,
        supportedBiometryType: 'FaceID',
        devicePasscodeAvailable: false,
        authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
        passwordIsAutoGenerated: false,
        t: (key: string) => key,
        isIOS: true,
      }).systemAuthTypeLabel,
    ).toBe('page.setting.faceId');

    expect(
      module.computeBiometricsState({
        authEnabled: true,
        supportedBiometryType: 'TouchID',
        devicePasscodeAvailable: false,
        authType: KEYCHAIN_AUTH_TYPES.BIOMETRICS_OR_PASSCODE,
        passwordIsAutoGenerated: false,
        t: (key: string) => key,
        isIOS: true,
      }).systemAuthTypeLabel,
    ).toBe('page.setting.touchId');
  });
});
