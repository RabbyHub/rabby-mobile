function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (reason: Error) => void;
  const promise = new Promise<T>((resolvePromise, rejectPromise) => {
    resolve = resolvePromise;
    reject = rejectPromise;
  });
  return { promise, resolve, reject };
}

describe('Sync Extension password preservation before navigation (QA 1068)', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    mockDecrypt.mockReset();
    mockSyncExtension.mockReset().mockResolvedValue([{ fixture: true }]);
  });

  async function enterPassword() {
    const view = render(<SyncExtensionPasswordScreen />);
    await act(async () => {});
    const input = view.UNSAFE_getByType(TextInput);
    fireEvent.changeText(input, FIXTURE_PASSWORD);
    return { view, input };
  }

  it('keeps the same controlled input and password while decrypt is pending', async () => {
    const pending = deferred<{ vault: unknown }>();
    mockDecrypt.mockReturnValue(pending.promise);
    const { view, input } = await enterPassword();

    fireEvent.press(view.getByText('global.Confirm'));

    expect(view.getByText('fixture-pending')).toBeTruthy();
    expect(mockDecrypt).toHaveBeenCalledWith(FIXTURE_PASSWORD, '{}');
    expect(view.UNSAFE_getByType(TextInput)).toBe(input);
    expect(input.props.value).toBe(FIXTURE_PASSWORD);
    expect(input.props.secureTextEntry).toBe(true);
    expect(mockReset).not.toHaveBeenCalled();

    await act(async () => pending.resolve({ vault: {} }));
  });

  it('retains the typed password after decrypt rejects and when the user retries', async () => {
    const pending = deferred<{ vault: unknown }>();
    mockDecrypt.mockReturnValueOnce(pending.promise);
    const logError = jest.spyOn(console, 'error').mockImplementation(() => {});
    try {
      const { view, input } = await enterPassword();
      fireEvent.press(view.getByText('global.Confirm'));
      await act(async () =>
        pending.reject(new Error('synthetic decrypt failure')),
      );

      expect(view.getByText('Error: synthetic decrypt failure')).toBeTruthy();
      expect(view.UNSAFE_getByType(TextInput)).toBe(input);
      expect(input.props.value).toBe(FIXTURE_PASSWORD);
      expect(mockReset).not.toHaveBeenCalled();

      mockDecrypt.mockResolvedValueOnce({ vault: {} });
      await act(async () => fireEvent.press(view.getByText('global.Confirm')));
      expect(mockDecrypt.mock.calls[1][0]).toBe(FIXTURE_PASSWORD);
    } finally {
      logError.mockRestore();
    }
  });

  it('does not clear the input before requesting the success route reset', async () => {
    mockDecrypt.mockResolvedValue({ vault: {} });
    const { view, input } = await enterPassword();
    mockReset.mockImplementationOnce(() => {
      expect(view.UNSAFE_getByType(TextInput)).toBe(input);
      expect(input.props.value).toBe(FIXTURE_PASSWORD);
    });

    await act(async () => fireEvent.press(view.getByText('global.Confirm')));

    expect(mockReset).toHaveBeenCalledTimes(1);
    expect(mockReset.mock.calls[0][0].routes[0].params.screen).toBe(
      'SyncExtensionAccountSuccess',
    );
    expect(view.UNSAFE_getByType(TextInput)).toBe(input);
    expect(input.props.value).toBe(FIXTURE_PASSWORD);
  });
});
